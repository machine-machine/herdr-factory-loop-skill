// ---- Pin: one deterministic script per group, run verbatim by a mechanical agent ----
function pinScript(g) {
  const lines = [
    'set -uo pipefail',
    'emit() { python3 -c \'import json,sys; a=sys.argv[1:]; print("HERD_PIN "+json.dumps(dict(zip(a[0::2],a[1::2]))))\' "$@"; }',
    'manifest_re=\'(^|/)(package(-lock)?\\.json|pnpm-lock\\.yaml|yarn\\.lock|pyproject\\.toml|uv\\.lock|poetry\\.lock|requirements[^/]*\\.txt)$\'',
    'pin_one() {',
    '  local key=$1 slice=$2 wt=$3 rev=$4 base=$5 n=$6 want=$7 reviewed=$8 setup=$9 repo=${10}',
    '  local warn="" head pin basesha created=0 setup_ok=true old="" changed=""',
    '  local i; for i in 1 2 3; do git -C "$wt" fetch -q origin "+refs/pull/$n/head:refs/remotes/origin/pr/$n" "+refs/heads/$base:refs/remotes/origin/$base" && break; [ $i = 3 ] && { emit key "$key" error "fetch failed (3 tries; parallel fetches share ref locks)"; return; }; sleep 3; done',
    '  head=$(git -C "$wt" rev-parse "refs/remotes/origin/pr/$n^{commit}") || { emit key "$key" error "no PR head"; return; }',
    '  pin=$head',
    '  if [ -n "$want" ]; then',
    '    if p=$(git -C "$wt" rev-parse --verify -q "$want^{commit}"); then pin=$p; else warn="accepted sha $want not found, pinned the current head"; fi',
    '  fi',
    '  [ "$pin" = "$head" ] || warn="${warn:+$warn; }head moved after acceptance — review covers the accepted sha"',
    '  basesha=$(git -C "$wt" rev-parse "refs/remotes/origin/$base^{commit}")',
    '  if [ -d "$rev" ]; then',
    '    old=$(git -C "$rev" rev-parse HEAD 2>/dev/null || true)',
    '    git -C "$rev" checkout -q --detach --force "$pin" || { emit key "$key" error "checkout of $pin in $rev failed"; return; }',
    '  else',
    '    git -C "$wt" worktree add -q --detach "$rev" "$pin" || { emit key "$key" error "worktree add $rev failed"; return; }',
    '    created=1',
    '  fi',
    '  if [ -n "$setup" ] && { [ $created = 1 ] || { [ -n "$old" ] && git -C "$rev" diff --name-only "$old" "$pin" | grep -qE "$manifest_re"; }; }; then',
    '    ( cd "$rev" && HERD_WT="$rev" HERD_SRC_WT="$wt" HERD_REPO="$repo" HERD_SLICE="$slice" HERD_SHA="$pin" bash -c "$setup" ) >"$rev.setup.log" 2>&1 || setup_ok=false',
    '  fi',
    '  if [ -n "$reviewed" ] && [ "$reviewed" != "$pin" ]; then',
    '    if r=$(git -C "$wt" rev-parse --verify -q "$reviewed^{commit}"); then',
    '      changed=$(git -C "$wt" range-diff --no-color "$(git -C "$wt" merge-base "$r" "$basesha")..$r" "$(git -C "$wt" merge-base "$pin" "$basesha")..$pin" | grep -cvE "^ *[0-9-]+: +[0-9a-f-]+ = " || true)',
    '    else changed=unknown; fi',
    '  elif [ -n "$reviewed" ]; then changed=0; fi',
    '  emit key "$key" slice "$slice" head "$head" pin "$pin" base_sha "$basesha" review_wt "$rev" created "$created" setup_ok "$setup_ok" \\',
    '    range_diff_changed "$changed" warn "$warn" files "$(git -C "$rev" diff --name-only "$basesha...$pin")"',
    '}',
  ]
  for (const pr of g.prs) {
    const slice = sliceOf(g, pr)
    const p = PRIOR[slice] || {}
    const want = p.phase === 'accepted' ? priorSha(p.prs, pr) : ''
    const reviewed = p.phase === 'review_ok' ? priorSha(p.prs, pr) : ''
    lines.push(`pin_one ${[keyOf(pr), slice, pr.wt, reviewWt(pr), base(pr.base), pr.n, want, reviewed, lookup(A.setup, pr), pr.repo].map(sq).join(' ')}`)
  }
  lines.push('echo HERD_PIN_DONE')
  return lines.join('\n')
}

function parsePins(stdout) {
  const out = {}
  for (const line of String(stdout || '').split('\n')) {
    if (!line.startsWith('HERD_PIN ')) continue
    try { const o = JSON.parse(line.slice(9)); out[o.key] = o } catch (e) { /* torn line: ignored, reported as missing pin */ }
  }
  return out
}

function hotReason(pr, pin) {
  const pats = HOT_DEFAULT.concat(lookup(A.hot, pr) || [])
  const files = String(pin.files || '').split('\n').filter(Boolean)
  const hit = files.find(f => pats.some(p => new RegExp(p, 'i').test(f)))
  if (base(pr.base) !== 'main') return `stacked on ${base(pr.base)} (merge probe)`
  return hit ? `touches ${hit}` : ''
}

function modeOf(g, pr, pin) {
  const p = PRIOR[sliceOf(g, pr)] || {}
  if (p.phase !== 'review_ok' || STALE === 'full') return 'full'
  return pin.range_diff_changed === '0' ? 'probe' : 'delta'
}

// ---- prompts ----
const reviewPrompt = (g, pr, pin, mode, hot) => {
  const slice = sliceOf(g, pr)
  const p = PRIOR[slice] || {}
  const what = mode === 'delta'
    ? `This is a DELTA review: the package was reviewed clean at ${priorSha(p.prs, pr)} and has been rebased since. Review only what changed: \`git -C ${pin.review_wt} range-diff <old-base>..${priorSha(p.prs, pr)} <new-base>..${pin.pin}\` (bases = merge-base with ${pin.base_sha}) and \`git -C ${pin.review_wt} diff ${priorSha(p.prs, pr)}..${pin.pin} -- <the PR's files>\`.`
    : `Review the full change: \`git -C ${pin.review_wt} diff ${pin.base_sha}...${pin.pin}\` plus \`gh pr view ${pr.n} -R ${pr.repo}\` for the description.`
  return `You are a strict code reviewer for ${pr.repo} PR #${pr.n}${pr.title ? ` ("${pr.title}")` : ''}, branch ${pr.head}, base ${base(pr.base)}. Herd package "${g.name}", slice ${slice}, review round ${ROUND}.
Your review worktree is ${pin.review_wt}, pinned at ${pin.pin} (detached). Do not use the worker's worktree ${pr.wt}.
${what}
${ctxFiles(slice, 'reviewer')} If earlier findings exist, first check whether each is fixed, then look for new problems in new commits.
${pr.note ? 'Orchestrator note: ' + pr.note + '\n' : ''}${hot ? `This change is hot (${hot}): read callers and migrations with extra care.\n` : ''}Read the surrounding code of every changed spot, not only the diff. Check:
1. Correctness: bugs, edge cases, wrong assumptions, regressions in callers (grep the callers); does the change do what the task asked for?
2. Safety/operations: permissions, data loss, secrets in code, anything that sends messages or mail.
3. Tests: run the tests of the touched modules in ${pin.review_wt}${lookup(A.tests, pr) ? ` (repo test command for reference: \`${lookup(A.tests, pr)}\` — narrow it to the touched files)` : ''}. Check whether the new tests would fail without the change.
4. Whether the PR text can be checked without prior knowledge.
Report ONLY real, concretely reproducible findings (input -> wrong result). No style or taste. Zero findings beats invented ones.
${RULES}`
}

const skepticPrompt = (g, pr, pin, f, k) => `Try to REFUTE this review finding (skeptic ${k + 1} of 2). ${pr.repo} PR #${pr.n}, pinned at ${pin.pin} in ${pin.review_wt} (read only).
Finding [${f.severity}] ${f.title} — ${f.file}${f.line ? ':' + f.line : ''}
${f.description}
Reviewer's repro: ${f.repro}
Check against the code at ${pin.pin} (tests or a small script in your own temp dir). refuted=true when the finding does not reproduce, was already so on ${base(pr.base)} before this PR, is intended (PR text, task, ${A.register ? A.register : 'decisions register if one exists'}), or has no real effect. When in doubt, refuted=true. severity_corrected: what the severity really is if it stands.
${ctxFiles(sliceOf(g, pr), 'reviewer')}
${RULES}`

function integPrompt(g, repo, mine, preds) {
  const first = mine[0].pr
  const wt = intWt(g, first)
  const fetches = mine.concat(preds).map(x => `+refs/pull/${x.pr.n}/head:refs/remotes/origin/pr/${x.pr.n}`).join(' ')
  const predList = preds.map(x => `${keyOf(x.pr)} (${x.group}, current head refs/remotes/origin/pr/${x.pr.n})`).join(', ') || 'none'
  const mineList = mine.map(x => `${keyOf(x.pr)} at ${x.pin}`).join(', ')
  const testCmd = lookup(A.tests, first)
  const setup = lookup(A.setup, first)
  return `Integration probe for ${repo}, package "${g.name}" (round ${ROUND}). Planned merge order puts these earlier packages before it: ${predList}.
1. \`git -C ${first.wt} fetch -q origin +refs/heads/main:refs/remotes/origin/main ${fetches}\`, then \`git -C ${first.wt} worktree add --detach ${wt} refs/remotes/origin/main\` (if ${wt} exists from an earlier run, remove it first with git worktree remove --force). Record \`git -C ${wt} rev-parse HEAD\` as main_sha (40 chars).
${setup ? `2. Setup: \`cd ${wt} && HERD_WT=${wt} HERD_SRC_WT=${first.wt} HERD_REPO=${first.repo} HERD_SLICE=${g.name}--int HERD_SHA=<main_sha> bash -c ${sq(setup)}\`.` : '2. No setup command is configured for this repo.'}
3. Baseline: merge the earlier packages one by one in the order above (\`git merge --no-ff --no-edit <ref>\`, local only). A conflict there is NOT this package's problem: \`git merge --abort\`, list it in predecessor_problems, skip it, continue.
4. ${testCmd ? `Run \`${testCmd}\` in ${wt} on the baseline; record counts and the failing test ids.` : 'No test command is configured: report "no tests configured" and do only the merge checks.'}
5. Candidate: merge this package's PRs in order: ${mineList}. A conflict: abort that merge, then check whether the same PR merges cleanly onto bare main (a second throwaway worktree at main_sha). Conflicts with main itself go to conflicts_main; conflicts that appear only on top of the earlier packages go to conflicts_predecessor, naming the other PR and the file.
6. ${testCmd ? `Run the same test command on the candidate. new_failures = tests failing on the candidate but not on the baseline; attribute each to one of ${mine.map(x => keyOf(x.pr)).join(', ')} (bisect by merging them one at a time when there are several), with the failing assertion as evidence. Flaky tests: re-run once before reporting.` : 'Skip.'}
7. Remove ${wt} and any second worktree (git worktree remove --force). Do not push, do not touch any PR branch.
${RULES}`
}

function surviving(rev, verdicts) {
  return verdicts.map(({ f, vs }) => {
    const ok = vs.filter(Boolean)
    if (!ok.length) return { ...f, votes: 0, survives: true, unverified: true, severity_final: f.severity, reasons: ['no skeptic answered — kept unverified'] }
    const conf = ok.filter(v => !v.refuted)
    const sev = conf.map(v => (v.severity_corrected === 'none' ? 'low' : v.severity_corrected)).sort((a, b) => SEV[b] - SEV[a])[0] || 'none'
    return { ...f, votes: ok.length, confirmed: conf.length, survives: conf.length >= 1 && conf.length >= ok.length / 2, severity_final: sev, reasons: ok.map(v => `${v.refuted ? 'refuted' : 'confirmed'}: ${v.reason}`) }
  })
}

async function reviewOne(g, pr, pin) {
  const mode = modeOf(g, pr, pin)
  const hot = hotReason(pr, pin)
  const key = keyOf(pr)
  if (mode === 'probe') return { pr: key, slice: sliceOf(g, pr), pin: pin.pin, mode, rev: null, findings: [] }
  const rev = await run(reviewPrompt(g, pr, pin, mode, hot), { label: `review:${g.name}:${key}`, phase: 'Review', schema: FINDINGS, model: reviewerModel(pr), effort: hot ? 'xhigh' : 'high' })
  if (!rev) return { pr: key, slice: sliceOf(g, pr), pin: pin.pin, mode, rev: null, findings: [], error: 'reviewer returned nothing' }
  const big = rev.findings.filter(f => f.severity !== 'low')
  const low = rev.findings.filter(f => f.severity === 'low')
  const judged = await parallel(big.map(f => () =>
    parallel([OPUS, FABLE].map((m, k) => () => run(skepticPrompt(g, pr, pin, f, k), { label: `verify:${g.name}:${key}:${k + 1}`, phase: 'Verify', schema: VERDICT, model: m, effort: 'medium' })))
      .then(vs => ({ f, vs }))))
  const findings = surviving(rev, judged.filter(Boolean))
    .concat(low.map(f => ({ ...f, votes: 0, survives: true, unverified: true, severity_final: 'low' })))
    .map(f => ({ ...f, pr: key, slice: sliceOf(g, pr) }))
  return { pr: key, slice: sliceOf(g, pr), pin: pin.pin, mode, hot, rev: { summary: rev.summary, tests: rev.tests, description_ok: rev.description_ok }, findings }
}

function integFindings(g, res, mine) {
  const out = []
  const keyToSlice = Object.fromEntries(mine.map(x => [keyOf(x.pr), sliceOf(g, x.pr)]))
  const pick = s => Object.keys(keyToSlice).find(k => String(s).includes(k)) || Object.keys(keyToSlice)[0]
  for (const c of res.conflicts_main || []) {
    const k = pick(c)
    out.push({ severity: 'high', severity_final: 'high', survives: true, title: `merge conflict with main: ${c}`, file: String(c).split(':').slice(1).join(':').trim() || '-', description: `The PR does not merge onto current main (${res.main_sha}).`, repro: `git merge --no-ff on main ${res.main_sha}`, pr: k, slice: keyToSlice[k], source: 'integration' })
  }
  for (const nf of res.new_failures || []) {
    const k = pick(nf.pr)
    out.push({ severity: 'high', severity_final: 'high', survives: true, title: `test fails only with this package: ${nf.test}`, file: nf.test, description: nf.evidence, repro: `merge onto main + earlier packages, run the repo tests (${res.candidate_result} vs baseline ${res.baseline_result})`, pr: k, slice: keyToSlice[k], source: 'integration' })
  }
  for (const c of res.conflicts_predecessor || []) {
    const k = pick(c)
    out.push({ severity: 'low', severity_final: 'low', survives: true, unverified: true, title: `rebase needed after an earlier package merges: ${c}`, file: '-', description: 'Conflicts only on top of an earlier package in the planned order; not blocking now.', repro: 'integration probe', pr: k, slice: keyToSlice[k], source: 'integration' })
  }
  return out
}

async function reviewGroup(g, gi) {
  const pr0 = await agent(`Run this bash script exactly as written (one Bash call, timeout 600000 ms; do not edit, split or "fix" it), then return its exit code and its COMPLETE stdout verbatim. Do nothing else.\n\n${pinScript(g)}`, { label: `pin:${g.name}`, phase: 'Pin', schema: PIN, model: OPUS, effort: 'low' })
  const pins = parsePins(pr0 && pr0.stdout)
  const missing = g.prs.filter(pr => !pins[keyOf(pr)] || pins[keyOf(pr)].error)
  if (missing.length) {
    const why = missing.map(pr => `${keyOf(pr)}: ${(pins[keyOf(pr)] || {}).error || 'no pin line'}`).join('; ')
    log(`${g.name}: pin failed — ${why}`)
    return { name: g.name, error: `pin failed: ${why}`, pins, reviews: [], integration: [], findings: [] }
  }
  for (const pr of g.prs) {
    const p = pins[keyOf(pr)]
    if (p.warn) log(`${g.name} ${keyOf(pr)}: ${p.warn}`)
    if (p.setup_ok === 'false') log(`${g.name} ${keyOf(pr)}: setup failed, see ${p.review_wt}.setup.log`)
  }
  // integration: per repo of this group, earlier packages (planned order) are the baseline
  const repos = [...new Set(g.prs.map(pr => pr.repo))]
  const probes = repos.map(repo => {
    const mine = g.prs.filter(pr => pr.repo === repo).map(pr => ({ pr, pin: pins[keyOf(pr)].pin }))
    const preds = GROUPS.slice(0, gi).flatMap(o => o.prs.filter(pr => pr.repo === repo).map(pr => ({ pr, group: o.name })))
    return () => agent(integPrompt(g, repo, mine, preds), { label: `integrate:${g.name}:${repoName(repo)}`, phase: 'Integrate', schema: INTEG, model: OPUS, effort: 'xhigh' })
      .then(res => ({ repo, res, mine }))
  })
  const reviews = g.prs.map(pr => () => reviewOne(g, pr, pins[keyOf(pr)]))
  const all = await parallel(reviews.concat(probes))
  const revs = all.slice(0, reviews.length)
  const ints = all.slice(reviews.length)
  const findings = revs.filter(Boolean).flatMap(r => r.findings.filter(f => f.survives))
  const integration = []
  ints.forEach((x, i) => {
    if (!x || !x.res) {
      const repo = repos[i]
      log(`${g.name}: integration probe for ${repo} returned nothing — blocking`)
      integration.push({ repo, error: 'probe returned nothing' })
      const pr = g.prs.find(p => p.repo === repo)
      findings.push({ severity: 'high', severity_final: 'high', survives: true, title: `integration probe for ${repoName(repo)} did not report`, file: '-', description: 'No probe result, so the package is not proven to merge onto current main.', repro: 're-run the loop', pr: keyOf(pr), slice: sliceOf(g, pr), source: 'integration' })
      return
    }
    integration.push(x.res)
    findings.push(...integFindings(g, x.res, x.mine))
  })
  revs.forEach((r, i) => {
    if (!r || r.error) {
      const pr = g.prs[i]
      findings.push({ severity: 'high', severity_final: 'high', survives: true, title: 'review did not complete', file: '-', description: (r && r.error) || 'review agent failed', repro: 're-run the loop', pr: keyOf(pr), slice: sliceOf(g, pr), source: 'review' })
    }
  })
  return { name: g.name, pins, reviews: revs.filter(Boolean), integration, findings, modes: Object.fromEntries(g.prs.map(pr => [keyOf(pr), modeOf(g, pr, pins[keyOf(pr)])])) }
}

const todo = GROUPS.map((g, gi) => ({ g, gi })).filter(x => !WANT || WANT.has(x.g.name))
if (!todo.length) log('review-open-prs: no group to review (check args.groups / args.review)')
const groups = await parallel(todo.map(x => () => reviewGroup(x.g, x.gi)))
return { round: ROUND, groups: groups.filter(Boolean) }
