// Contract: docs/herd-flow-v2.md §5. This script never writes herd state; review-fix-loop.js does.
// args (all from the orchestrator, nothing hard-coded):
//   herd            absolute herd dir (optional standalone; used for task/out/ctx/befunde paths)
//   groups          [{name, slices, prs:[{repo, short, n, head, base, wt, worker_model, slice?, review_wt?, title?, note?}]}]
//                   in PLANNED MERGE ORDER — the integration probe merges predecessors in this order
//   review          group names to review this call (default: all groups)
//   prior           {<slice>: last herd event} from review-fix-loop's start step (optional)
//   round           review round, 1-based (default 1)
//   setup           {<repo>: shell command run inside a fresh review/probe worktree}
//   tests           {<repo>: shell command for the touched suites}
//   reviewModel     'other' (default) | 'same'
//   stale           'delta' (default) | 'full' — only matters when a slice's prior phase is review_ok
//   models          {opus, fable} model ids (defaults claude-opus-5-5, claude-fable-5-1)
//   hot             {<repo>: [regex strings]} extra hot-file patterns (effort xhigh)
//   rules           extra project rules appended to every prompt (one paragraph)
//   register        optional path of a decisions register reviewers consult
//   lang            language of findings text (default English)

const A = args || {}
const GROUPS = A.groups || []
const WANT = A.review && A.review.length ? new Set(A.review) : null
const PRIOR = A.prior || {}
const ROUND = A.round || 1
const STALE = A.stale === 'full' ? 'full' : 'delta'
const OPUS = (A.models && A.models.opus) || 'claude-opus-5-5'
const FABLE = (A.models && A.models.fable) || 'claude-fable-5-1'
const LANG = A.lang || 'English'
const SEV = { none: 0, low: 1, medium: 2, high: 3 }
const HOT_DEFAULT = ['(^|/)migrations?/', 'alembic/', '(^|/)auth', 'login', 'session', 'token', 'permission', 'rollen', '\\.sql$', '(^|/)Dockerfile$', 'docker-compose']

function sq(s) { return "'" + String(s).replace(/'/g, "'\\''") + "'" }
function base(r) { return String(r || '').replace(/^origin\//, '') }
function repoName(r) { return String(r).split('/').pop() }
function keyOf(pr) { return `${pr.short}#${pr.n}` }
function lookup(map, pr) {
  if (!map) return ''
  return map[pr.repo] || map[repoName(pr.repo)] || map[pr.short] || ''
}
function sliceOf(g, pr) {
  if (pr.slice) return pr.slice
  const b = String(pr.wt || '').replace(/\/+$/, '').split('/').pop()
  if ((g.slices || []).includes(b)) return b
  if ((g.slices || []).length === 1) return g.slices[0]
  throw new Error(`group ${g.name}: cannot tell the slice of ${keyOf(pr)} — set pr.slice`)
}
function reviewWt(pr) { return pr.review_wt || `${String(pr.wt).replace(/\/+$/, '')}--review` }
function intWt(g, pr) { return `${String(pr.wt).replace(/\/+$/, '').split('/').slice(0, -1).join('/')}/${g.name}--int` }
// prior event lists look like ["api#210@6cb1f80", ...]; match on number + repo spelling
function priorSha(list, pr) {
  for (const s of list || []) {
    const m = /^([^#@\s]+)#(\d+)@([0-9a-f]{7,40})$/.exec(String(s).trim())
    if (m && +m[2] === +pr.n && [pr.short, pr.repo, repoName(pr.repo)].includes(m[1])) return m[3]
  }
  return ''
}
function otherModel(m) { return /fable/i.test(m || '') ? OPUS : FABLE }
function reviewerModel(pr) {
  const w = pr.worker_model || OPUS
  return A.reviewModel === 'same' ? w : otherModel(w)
}
async function run(prompt, opts) {
  // per-agent model, no inheritance; fall back to Opus when the chosen model is unavailable
  const r = await agent(prompt, opts)
  if (r != null || opts.model === OPUS) return r
  log(`${opts.label}: ${opts.model} gave no result, retrying with ${OPUS}`)
  return agent(prompt, { ...opts, model: OPUS, label: `${opts.label}~opus` })
}
function ctxFiles(slice, role) {
  if (!A.herd) return ''
  const h = A.herd.replace(/\/+$/, '')
  return `Context (read what exists, skip what is missing): ${h}/${slice}.ctx.${role}.md (generated by herd-context), ${h}/${slice}.task.md (task + header), ${h}/${slice}.out.md (worker report), earlier findings ${h}/${slice}.befunde-*.md.${A.register ? ` Decisions register: ${A.register} — a recorded decision is intent, not a bug.` : ''}`
}

const RULES = `Hard rules: work locally only. Never read credentials (credential stores, .env contents, token files) and never call staging or external services; reading GitHub with gh is fine. No push, no merge, no PR comments, no tickets, no mail. Never modify the worker's worktree or the PR branch; the <slice>--review worktree is pinned read-only for you — put any repro script or extra test under your own temp dir, never commit there. Never pkill/pgrep -f; stop processes by pid. Remove throwaway worktrees you create yourself (git worktree remove --force). Write findings text in ${LANG}.${A.rules ? '\n' + A.rules : ''}`

